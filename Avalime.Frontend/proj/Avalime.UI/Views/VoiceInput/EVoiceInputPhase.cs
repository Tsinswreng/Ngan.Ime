namespace Avalime.UI.Views.VoiceInput;

/// 語音輸入頁一次識別會話的前端階段。
/// 此枚舉只描述 UI 可觀察的生命週期，不綁定火山引擎或任何特定供應商的協議狀態。
/// Provider 適配器後續需要把自身的連接、錄音、等待尾包及錯誤狀態映射到這組穩定階段。
public enum EVoiceInputPhase{
	/// 尚未開始識別；允許選擇語言、編輯草稿、清空及上屏。
	Idle = 0,

	/// 正在申請麥克風、初始化錄音設備或建立遠端連接。
	/// 此階段禁止重複開始，避免同時建立多個錄音與 WebSocket 會話。
	Starting,

	/// 麥克風音頻正在持續送往識別服務。
	/// 文本框展示流式結果，但暫時禁止人工編輯，以免服務端更新覆蓋用戶修改。
	Recording,

	/// 用戶已停止錄音，但服務端仍可能返回最後一批穩定文本。
	/// UI 應保留等待狀態，不能過早允許上屏或開始下一輪識別。
	Finalizing,

	/// 本輪識別正常完成；文本框重新允許人工編輯，且可由用戶決定是否上屏。
	Completed,

	/// 本輪因設備、網絡、鑒權、限額或供應商錯誤而終止。
	/// 已經取得的文本仍保留，避免短暫故障導致識別成果丟失。
	Failed,
}
